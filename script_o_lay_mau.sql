CREATE OR REPLACE VIEW V_HIS_TREATMENT_SAMPLE_DESK
AS SELECT TSD.*,
TREA.TREATMENT_CODE,
TREA.TDL_PATIENT_CODE,
TREA.TDL_PATIENT_NAME,
TREA.TDL_PATIENT_DOB,
TREAT.TREATMENT_TYPE_NAME,
PTT.PATIENT_TYPE_NAME,
SAR.SAMPLE_ROOM_NAME,
SAD.SAMPLE_DESK_NAME,
(CASE WHEN PAID = PAYMENT THEN 1 END) IS_PAID,
(CASE WHEN PAYMENT = PAYMENT_BHYT THEN 1 END) IS_BHYT,
(CASE WHEN PAID = PAYMENT OR PAYMENT = PAYMENT_BHYT THEN 1 END) IS_BHYT_OR_PAID
FROM HIS_TREATMENT_SAMPLE_DESK TSD
JOIN HIS_TREATMENT TREA ON TREA.ID = TSD.TREATMENT_ID
JOIN HIS_SAMPLE_ROOM SAR ON SAR.ID = TSD.SAMPLE_ROOM_ID
JOIN HIS_PATIENT_TYPE PTT ON PTT.ID = TSD.TDL_PATIENT_TYPE_ID
JOIN HIS_TREATMENT_TYPE TREAT ON TREAT.ID = TREA.TDL_TREATMENT_TYPE_ID
LEFT JOIN HIS_SAMPLE_DESK SAD ON SAD.ID = TSD.SAMPLE_DESK_ID
LEFT JOIN LATERAL
(SELECT /*+ NO_RESULT_CACHE */SUM(SSB.PRICE) PAID, SUM(SS.VIR_TOTAL_PATIENT_PRICE) PAYMENT, SUM(SS.VIR_TOTAL_PATIENT_PRICE_BHYT) PAYMENT_BHYT 
FROM HIS_SERE_SERV SS
JOIN HIS_SERVICE_REQ SR ON SR.ID = SS.SERVICE_REQ_ID
LEFT JOIN HIS_SERE_SERV_BILL SSB ON SSB.SERE_SERV_ID = SS.ID AND SSB.TDL_TREATMENT_ID = TSD.TREATMENT_ID
WHERE SS.IS_DELETE=0 AND SS.IS_NO_EXECUTE IS NULL AND SSB.IS_CANCEL IS NULL
AND SR.IS_DELETE=0 AND SR.IS_NO_EXECUTE IS NULL
AND SR.SAMPLE_ROOM_ID = TSD.SAMPLE_ROOM_ID
AND SR.TREATMENT_ID = TSD.TREATMENT_ID) ON 1=1
WHERE TSD.IS_DELETE = 0;

  CREATE OR REPLACE EDITIONABLE TRIGGER "HIS_RS"."HIS_SERVICE_REQ_101" BEFORE INSERT OR UPDATE ON HIS_SERVICE_REQ FOR EACH ROW
