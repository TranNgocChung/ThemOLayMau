BEGIN
 IF :NEW.SAMPLE_ROOM_ID IS NOT NULL AND (:OLD.SAMPLE_ROOM_ID IS NULL OR :OLD.SAMPLE_ROOM_ID <> :NEW.SAMPLE_ROOM_ID) THEN
   INSERT INTO HIS_TREATMENT_SAMPLE_DESK (TREATMENT_ID,SAMPLE_ROOM_ID,TDL_IS_PRIORITY,TDL_PATIENT_TYPE_ID,TDL_TREATMENT_TYPE_ID) 
   SELECT :NEW.TREATMENT_ID,:NEW.SAMPLE_ROOM_ID,:NEW.PRIORITY,:NEW.TDL_PATIENT_TYPE_ID,:NEW.TDL_TREATMENT_TYPE_ID FROM DUAL WHERE NOT EXISTS (SELECT 1 FROM HIS_TREATMENT_SAMPLE_DESK WHERE TREATMENT_ID = :NEW.TREATMENT_ID AND SAMPLE_ROOM_ID = :NEW.SAMPLE_ROOM_ID AND SAMPLE_DESK_ID IS NULL);
